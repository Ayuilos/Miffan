package me.rerere.rdp

/** Set-1 scancodes; bit 8 denotes an extended (E0) key. Text uses Unicode events instead. */
internal object RdpKeys {
    private val letters = intArrayOf(0x1e,0x30,0x2e,0x20,0x12,0x21,0x22,0x23,0x17,0x24,0x25,0x26,0x32,0x31,0x18,0x19,0x10,0x13,0x1f,0x14,0x16,0x2f,0x11,0x2d,0x15,0x2c)
    fun scancode(keysym: Int): Int? = when (keysym) {
        in 'a'.code..'z'.code -> letters[keysym - 'a'.code]
        in 'A'.code..'Z'.code -> letters[keysym - 'A'.code]
        in '1'.code..'9'.code -> keysym - '1'.code + 2
        '0'.code -> 0x0b
        0xff08 -> 0x0e; 0xff09 -> 0x0f; 0xff0d -> 0x1c; 0xff1b -> 1
        0xffff -> 0x153; 0xff50 -> 0x147; 0xff51 -> 0x14b; 0xff52 -> 0x148
        0xff53 -> 0x14d; 0xff54 -> 0x150; 0xff55 -> 0x149; 0xff56 -> 0x151; 0xff57 -> 0x14f
        in 0xffbe..0xffc7 -> 0x3b + keysym - 0xffbe
        0xffc8 -> 0x57; 0xffc9 -> 0x58
        0xffe1 -> 0x2a; 0xffe2 -> 0x36; 0xffe3 -> 0x1d; 0xffe4 -> 0x11d
        0xffe7,0xffeb -> 0x15b; 0xffe8,0xffec -> 0x15c
        0xffe9 -> 0x38; 0xffea -> 0x138
        ' '.code -> 0x39; '-'.code,'_'.code -> 0x0c; '='.code,'+'.code -> 0x0d
        '['.code,'{'.code -> 0x1a; ']'.code,'}'.code -> 0x1b
        ';'.code,':'.code -> 0x27; '\''.code,'"'.code -> 0x28
        '`'.code,'~'.code -> 0x29; '\\'.code,'|'.code -> 0x2b
        ','.code,'<'.code -> 0x33; '.'.code,'>'.code -> 0x34; '/'.code,'?'.code -> 0x35
        '!'.code -> 2; '@'.code -> 3; '#'.code -> 4; '$'.code -> 5; '%'.code -> 6
        '^'.code -> 7; '&'.code -> 8; '*'.code -> 9; '('.code -> 10; ')'.code -> 11
        else -> null
    }
}
